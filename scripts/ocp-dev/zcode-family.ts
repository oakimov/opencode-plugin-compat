/**
 * ZCode family: the external `ocp zcode` bridge behind a stock ZCode install.
 *
 * ZCode is not an OpenCode clone, not Pi and not DSH: it loads no OpenCode
 * plugin. OCP runs the unchanged provider in its own process and ZCode reaches
 * it as a Personal provider using Anthropic Messages. The shim therefore:
 *
 *   1. prepares the bridge (this checkout, or published `@opencode-compat/ocp`)
 *      behind an isolated OCP home under the ocp-dev state dir, with an
 *      `ocp-zcode` wrapper that sets that home;
 *   2. links the provider checkout (local) or installs the published provider
 *      (npm) into that home's install root, and writes the bridge config;
 *   3. inserts one Personal provider rule into ZCode's documented
 *      `provider_config.json` (apps/zcode-cli/docs/usage/03-config.md),
 *      surgically, leaving every other provider, model rule and selection intact.
 *
 * ZCode itself is never modified, and its private lock protocol is not
 * reimplemented: wiring refuses to run while ZCode is open.
 */
import { existsSync, lstatSync, mkdirSync, readFileSync, rmSync, symlinkSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join } from "node:path"
import { generateCredential } from "../../packages/cli/src/zcode/credentials.ts"
import { configFile, type WireMode } from "./hosts.ts"
import { deletePath, getNode, parseJsonc, pushPath, setPath, toValue } from "./jsonc.ts"
import {
  assertManaged,
  defaultProviderPath,
  fileMode,
  hostStateDir,
  manifestPath,
  pluginName,
  readText,
  repoRoot,
  writeAtomic,
} from "./paths.ts"
import { assertSafeProvider, assertStockClean, ensureStockBuild } from "./stock.ts"

/** The Personal provider id this shim owns in ZCode's provider_config.json. */
export const ZCODE_PROVIDER_ID = "ocp-dev"
export const ZCODE_BINDING_ID = "ocp-dev"
export const ZCODE_PLUGIN_ID = "provider"
export const ZCODE_DEFAULT_PORT = 18731
const SUPPORTED_SCHEMA_VERSION = 1

export function zcodeStateDir(): string {
  return hostStateDir("zcode")
}

/** Isolated OCP home: the bridge's XDG config/data/cache roots. */
export function zcodeHome(): string {
  return join(zcodeStateDir(), "home")
}

export function zcodeBridgeEnv(home = zcodeHome()): Record<string, string> {
  return {
    XDG_CONFIG_HOME: join(home, "config"),
    XDG_DATA_HOME: join(home, "data"),
    XDG_CACHE_HOME: join(home, "cache"),
  }
}

export function zcodeWrapperPath(): string {
  return join(zcodeStateDir(), "bin", "ocp-zcode")
}

function bridgeConfigPath(home = zcodeHome()): string {
  return join(home, "config", "opencode-compat", "zcode-bridge.json")
}

function installRoot(home = zcodeHome()): string {
  return join(home, "data", "opencode-compat", "zcode", "plugins")
}

/** Kept on unshim: upstream auth and the bridge credential. */
function retainedStateDir(home = zcodeHome()): string {
  return join(home, "data", "opencode-compat", "zcode", "state")
}

function credentialPath(home = zcodeHome()): string {
  return join(retainedStateDir(home), "model-credential")
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`
}

/** `ocp-zcode` wrapper: the chosen bridge entry under the isolated OCP home. */
export function zcodeWrapperScript(entry: string, mode: WireMode, home = zcodeHome()): string {
  const env = zcodeBridgeEnv(home)
  return [
    "#!/bin/sh",
    `# generated by ocp-dev (zcode, ${mode}) — rerun scripts/ocp-dev.sh run zcode to update`,
    ...Object.entries(env).map(([name, value]) => `export ${name}=${shellQuote(value)}`),
    `exec bun ${shellQuote(entry)} zcode "$@"`,
    "",
  ].join("\n")
}

export type ZcodeBridgeConfigInput = {
  port: number
  workspace: string
  credentialFile: string
  plugin: string
  version: string
}

/** The bridge config ocp-dev owns: one binding, the provider's whole catalog. */
export function zcodeBridgeConfig(input: ZcodeBridgeConfigInput): Record<string, unknown> {
  return {
    version: 1,
    listen: { host: "127.0.0.1", port: input.port },
    bindings: [{
      id: ZCODE_BINDING_ID,
      workspace: input.workspace,
      credentials: { model: { file: input.credentialFile } },
      plugins: [{
        id: ZCODE_PLUGIN_ID,
        package: input.plugin,
        version: input.version,
        contract: "classic",
        models: "catalog",
      }],
    }],
  }
}

export type ZcodeProviderRule = {
  providerId: string
  providerName: string
  config: {
    group: "standard-personal"
    access: { type: "api-key"; apiKey: string }
    api: { type: "anthropic-messages"; baseUrl: string }
    personalModelIds: string[]
  }
}

export function zcodeProviderRule(input: { port: number; credential: string; modelIds: string[] }): ZcodeProviderRule {
  return {
    providerId: ZCODE_PROVIDER_ID,
    providerName: "OCP (ocp-dev)",
    config: {
      group: "standard-personal",
      access: { type: "api-key", apiKey: input.credential },
      api: { type: "anthropic-messages", baseUrl: `http://127.0.0.1:${input.port}/v1` },
      personalModelIds: input.modelIds,
    },
  }
}

const RULES_PATH = ["config", "providerConfigRules", "providerRules"]
const ORDER_PATH = ["config", "providerOrder"]

function readProviderConfig(configPath: string): { text: string; root: ReturnType<typeof parseJsonc> } {
  const text = readText(configPath) ?? ""
  const root = parseJsonc(text)
  if (root.type !== "object") throw new Error(`${configPath} is not a JSON object`)
  const versionNode = getNode(root, ["schemaVersion"])
  const version = versionNode ? toValue(versionNode) : undefined
  if (version !== SUPPORTED_SCHEMA_VERSION) {
    throw new Error(`${configPath} has schemaVersion ${JSON.stringify(version)}; ocp-dev only edits schemaVersion ${SUPPORTED_SCHEMA_VERSION}`)
  }
  return { text, root }
}

function ruleIndexes(root: ReturnType<typeof parseJsonc>, providerId: string): number[] {
  const node = getNode(root, RULES_PATH)
  if (!node) return []
  if (node.type !== "array") throw new Error("config.providerConfigRules.providerRules is not an array")
  const indexes: number[] = []
  ;(toValue(node) as unknown[]).forEach((rule, index) => {
    if (rule && typeof rule === "object" && (rule as { providerId?: unknown }).providerId === providerId) indexes.push(index)
  })
  return indexes
}

function ownedRuleIndexes(root: ReturnType<typeof parseJsonc>, providerId: string, credential: string | undefined): number[] {
  const indexes = ruleIndexes(root, providerId)
  for (const index of indexes) {
    const rule = toValue(getNode(root, [...RULES_PATH, index])!) as Partial<ZcodeProviderRule>
    if (!credential || rule.providerName !== "OCP (ocp-dev)" ||
        rule.config?.api?.type !== "anthropic-messages" || rule.config.access?.apiKey !== credential) {
      throw new Error(`ZCode provider id "${providerId}" is already in use by a Personal provider outside this shim`)
    }
  }
  return indexes
}

/**
 * Insert or replace this shim's provider rule in an existing
 * provider_config.json. The file is never created here: ZCode imports a
 * user's legacy config.json only while provider_config.json is absent
 * (apps/zcode-cli/docs/usage/03-config.md), so ZCode must create it first.
 * Returns whether the provider id was appended to an existing providerOrder.
 */
export function upsertZcodeProvider(configPath: string, rule: ZcodeProviderRule): { appendedOrder: boolean } {
  if (!existsSync(configPath)) {
    throw new Error(`${configPath} does not exist. Start ZCode once (it creates the file and imports any legacy provider settings), quit it, then rerun.`)
  }
  const mode = fileMode(configPath) ?? 0o600
  let text = readProviderConfig(configPath).text
  const root = parseJsonc(text)
  const existing = ownedRuleIndexes(root, rule.providerId, rule.config.access.apiKey)
  if (existing.length === 0) {
    text = pushPath(text, RULES_PATH, rule)
  } else {
    text = setPath(text, [...RULES_PATH, existing[0]!], rule)
    for (let i = existing.length - 1; i >= 1; i -= 1) text = deletePath(text, [...RULES_PATH, existing[i]!])
  }
  let appendedOrder = false
  const order = getNode(parseJsonc(text), ORDER_PATH)
  if (order) {
    if (order.type !== "array") throw new Error("config.providerOrder is not an array")
    if (!(toValue(order) as unknown[]).includes(rule.providerId)) {
      text = pushPath(text, ORDER_PATH, rule.providerId)
      appendedOrder = true
    }
  }
  // Never widen a user's file permissions; the rule carries a credential.
  writeAtomic(configPath, text.endsWith("\n") ? text : `${text}\n`, mode & 0o600)
  return { appendedOrder }
}

export type ZcodeRemoval = { removedRules: number; removedModelRules: number; removedOrder: boolean; clearedSelection: boolean }

/**
 * Remove this shim's provider rule, model rules that name it, its
 * providerOrder entry (only when this shim appended it) and a default model
 * selection that points at it. Everything else is left byte-for-byte.
 */
export function removeZcodeProvider(configPath: string, providerId: string, options: { removeOrder: boolean; credential: string | undefined }): ZcodeRemoval {
  const result: ZcodeRemoval = { removedRules: 0, removedModelRules: 0, removedOrder: false, clearedSelection: false }
  if (!existsSync(configPath)) return result
  const mode = fileMode(configPath)
  const loaded = readProviderConfig(configPath)
  let text = loaded.text
  const root = loaded.root
  const rules = ownedRuleIndexes(root, providerId, options.credential)
  if (rules.length === 0) return result
  for (let i = rules.length - 1; i >= 0; i -= 1) text = deletePath(text, [...RULES_PATH, rules[i]!])
  result.removedRules = rules.length

  for (const kind of ["providerModelRules", "manualProviderModelRules"]) {
    const path = ["config", "modelConfigRules", kind]
    const node = getNode(parseJsonc(text), path)
    if (!node || node.type !== "array") continue
    const values = toValue(node) as unknown[]
    for (let i = values.length - 1; i >= 0; i -= 1) {
      const value = values[i]
      if (value && typeof value === "object" && (value as { providerId?: unknown }).providerId === providerId) {
        text = deletePath(text, [...path, i])
        result.removedModelRules += 1
      }
    }
  }

  if (options.removeOrder) {
    const order = getNode(parseJsonc(text), ORDER_PATH)
    if (order?.type === "array") {
      const values = toValue(order) as unknown[]
      for (let i = values.length - 1; i >= 0; i -= 1) {
        if (values[i] === providerId) {
          text = deletePath(text, [...ORDER_PATH, i])
          result.removedOrder = true
        }
      }
    }
  }

  const selection = getNode(parseJsonc(text), ["config", "defaultModelSelection"])
  if (selection && (toValue(selection) as { providerId?: unknown } | undefined)?.providerId === providerId) {
    text = deletePath(text, ["config", "defaultModelSelection"])
    result.clearedSelection = true
  }
  writeAtomic(configPath, text.endsWith("\n") ? text : `${text}\n`, mode)
  return result
}

/** ZCode Desktop or CLI processes, which hold provider_config.json open. */
export function zcodeRunning(): boolean {
  for (const pattern of ["ZCode.app/Contents/MacOS/", "(^|/)zcode( |$)"]) {
    const result = Bun.spawnSync({ cmd: ["pgrep", "-f", pattern], stdout: "pipe", stderr: "pipe" })
    if (result.exitCode === 0) return true
  }
  return false
}

function assertZcodeClosed(): void {
  if (zcodeRunning()) {
    throw new Error("ZCode is running. Quit ZCode (Desktop and CLI) first: it holds provider_config.json under its own lock and would overwrite this edit.")
  }
}

function run(cwd: string | undefined, cmd: string[], env?: Record<string, string>): void {
  const result = Bun.spawnSync({ cmd, cwd, stdout: "inherit", stderr: "inherit", env: { ...process.env, ...env } })
  if (result.exitCode !== 0) throw new Error(`${cmd.join(" ")} failed`)
}

function capture(cmd: string[], env?: Record<string, string>): { ok: boolean; stdout: string; stderr: string } {
  const result = Bun.spawnSync({ cmd, stdout: "pipe", stderr: "pipe", env: { ...process.env, ...env } })
  return { ok: result.exitCode === 0, stdout: result.stdout.toString(), stderr: result.stderr.toString() }
}

function removeManaged(path: string): void {
  assertManaged(path)
  rmSync(path, { recursive: true, force: true })
}

function ensurePrivatePackage(dir: string, name: string): void {
  mkdirSync(dir, { recursive: true })
  const manifest = join(dir, "package.json")
  if (!existsSync(manifest)) writeAtomic(manifest, `${JSON.stringify({ name, private: true }, null, 2)}\n`)
}

function readVersion(packageDir: string): string {
  const version = (JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8")) as { version?: unknown }).version
  if (typeof version !== "string") throw new Error(`${packageDir}/package.json has no version`)
  return version
}

/** Resolve an npm tag or version to the exact published version. */
function exactNpmVersion(name: string, tag: string): string {
  const result = capture(["npm", "view", `${name}@${tag}`, "version", "--json"])
  if (!result.ok) throw new Error(`npm view ${name}@${tag} failed: ${result.stderr.trim()}`)
  const parsed = JSON.parse(result.stdout) as unknown
  const version = Array.isArray(parsed) ? parsed.at(-1) : parsed
  if (typeof version !== "string") throw new Error(`npm view ${name}@${tag} returned no version`)
  return version
}

function ensureCredential(): string {
  const file = credentialPath()
  assertManaged(file)
  const existing = readText(file)?.trim()
  if (existing) return existing
  const value = generateCredential()
  writeAtomic(file, `${value}\n`, 0o600)
  return value
}

/** Link the provider checkout into the isolated install root (local mode). */
function linkLocalProvider(provider: string, plugin: string): void {
  const root = installRoot()
  assertManaged(root)
  ensurePrivatePackage(root, "ocp-dev-zcode-plugins")
  const target = join(root, "node_modules", ...plugin.split("/"))
  if (lstatSync(target, { throwIfNoEntry: false })) removeManaged(target)
  mkdirSync(dirname(target), { recursive: true })
  symlinkSync(provider, target)
}

function prepareLocal(provider: string): string {
  const root = repoRoot()
  console.log("ocp-dev: installing locked OCP workspace dependencies")
  run(root, ["bun", "install", "--frozen-lockfile"])
  console.log("ocp-dev: building OCP")
  run(root, ["bun", "run", "build"])
  const entry = join(root, "packages", "ocp", "bin", "ocp.ts")
  if (!existsSync(join(root, "packages", "cli", "dist", "zcode", "cli.js"))) throw new Error("OCP CLI zcode entry missing after build")
  assertSafeProvider(provider)
  assertStockClean(provider)
  ensureStockBuild(provider)
  return entry
}

function prepareNpm(): { entry: string; version: string } {
  const tag = process.env.OCP_DEV_BRIDGE_VERSION || "latest"
  const version = exactNpmVersion("@opencode-compat/ocp", tag)
  const dir = join(zcodeStateDir(), "npm")
  assertManaged(dir)
  ensurePrivatePackage(dir, "ocp-dev-zcode-bridge")
  console.log(`ocp-dev: installing @opencode-compat/ocp@${version}`)
  run(dir, ["bun", "add", "--exact", `@opencode-compat/ocp@${version}`])
  return { entry: join(dir, "node_modules", "@opencode-compat", "ocp", "bin", "ocp.ts"), version }
}

/**
 * Whether this shim owns the `providerOrder` entry. A later run that finds
 * the id already present (because an earlier run added it) keeps that
 * ownership for the same config file, so unshim still removes it.
 */
export function ownsProviderOrder(previousManifest: string | undefined, configPath: string, appendedNow: boolean): boolean {
  if (appendedNow) return true
  if (!previousManifest) return false
  try {
    const previous = JSON.parse(previousManifest) as { configPath?: unknown; appendedOrder?: unknown }
    return previous.configPath === configPath && previous.appendedOrder === true
  } catch {
    return false
  }
}

export async function runZcode(mode: WireMode): Promise<void> {
  assertZcodeClosed()
  const configPath = configFile("zcode")
  if (!existsSync(configPath)) {
    throw new Error(`${configPath} does not exist. Start ZCode once (it creates the file and imports any legacy provider settings), quit it, then rerun.`)
  }
  ownedRuleIndexes(readProviderConfig(configPath).root, ZCODE_PROVIDER_ID, readText(credentialPath())?.trim())
  const plugin = pluginName()
  const port = Number(process.env.OCP_DEV_ZCODE_PORT || ZCODE_DEFAULT_PORT)
  if (!Number.isInteger(port) || port < 1 || port > 65_535) throw new Error("OCP_DEV_ZCODE_PORT must be an integer between 1 and 65535")
  const workspace = process.env.OCP_DEV_ZCODE_WORKSPACE || process.env.HOME || homedir()
  const env = zcodeBridgeEnv()

  let entry: string
  let version: string
  let bridge = "this OCP checkout"
  if (mode === "local") {
    const provider = defaultProviderPath()
    entry = prepareLocal(provider)
    version = readVersion(provider)
    linkLocalProvider(provider, plugin)
  } else {
    const published = prepareNpm()
    entry = published.entry
    bridge = `the published @opencode-compat/ocp@${published.version}`
    // A local-mode symlink must not shadow the published install.
    const linked = join(installRoot(), "node_modules", ...plugin.split("/"))
    if (lstatSync(linked, { throwIfNoEntry: false })?.isSymbolicLink()) removeManaged(linked)
    version = exactNpmVersion(plugin, process.env.OCP_DEV_PLUGIN_VERSION || "latest")
  }

  const wrapper = zcodeWrapperPath()
  assertManaged(wrapper)
  writeAtomic(wrapper, zcodeWrapperScript(entry, mode), 0o755)
  const help = capture([wrapper, "help"])
  if (!help.ok) {
    const detail = (help.stderr || help.stdout).trim()
    throw new Error(`${bridge} has no working "ocp zcode" command${mode === "npm" ? " (npm mode needs a release that includes it; set OCP_DEV_BRIDGE_VERSION)" : ""}${detail ? `:\n${detail}` : ""}`)
  }
  if (mode === "npm") run(undefined, [wrapper, "install", `${plugin}@${version}`])

  const credential = ensureCredential()
  writeAtomic(bridgeConfigPath(), `${JSON.stringify(zcodeBridgeConfig({ port, workspace, credentialFile: credentialPath(), plugin, version }), null, 2)}\n`, 0o600)

  const listed = capture([wrapper, "models", "--json"], env)
  if (!listed.ok) throw new Error(`ocp zcode models failed:\n${listed.stderr || listed.stdout}`)
  const rows = JSON.parse(listed.stdout) as Array<{ id: string; auth: string }>
  const modelIds = rows.map(row => row.id)
  const loginRequired = rows.some(row => row.auth === "login-required") || (rows.length === 0)

  const previousManifest = readText(manifestPath("zcode"))
  const appendedOrder = ownsProviderOrder(
    previousManifest,
    configPath,
    upsertZcodeProvider(configPath, zcodeProviderRule({ port, credential, modelIds })).appendedOrder,
  )
  writeAtomic(manifestPath("zcode"), `${JSON.stringify({
    host: "zcode", mode, plugin, version, port, configPath, providerId: ZCODE_PROVIDER_ID, appendedOrder, wrapper,
    updated: new Date().toISOString(),
  }, null, 2)}\n`)

  console.log(`\nocp-dev: zcode is on ${mode.toUpperCase()} ocp zcode + ${mode.toUpperCase()} ${plugin}@${version}`)
  console.log(`  ZCode config: ${configPath} (Personal provider "${ZCODE_PROVIDER_ID}", ${modelIds.length} model(s))`)
  console.log(`  bridge: ${wrapper} serve`)
  if (loginRequired) {
    console.log(`  login:  ${wrapper} auth --binding ${ZCODE_BINDING_ID} --plugin ${ZCODE_PLUGIN_ID}`)
    console.log("          then rerun scripts/ocp-dev.sh run zcode so ZCode lists the plugin's models")
  }
  console.log("  verify: start the bridge, open ZCode, pick an OCP (ocp-dev) model in a new session")
}

export async function unshimZcode(): Promise<void> {
  assertZcodeClosed()
  const manifestText = readText(manifestPath("zcode"))
  const manifest = manifestText ? JSON.parse(manifestText) as { appendedOrder?: boolean; configPath?: string } : {}
  const configPath = manifest.configPath ?? configFile("zcode")
  const removal = removeZcodeProvider(configPath, ZCODE_PROVIDER_ID, {
    removeOrder: manifest.appendedOrder === true,
    credential: readText(credentialPath())?.trim(),
  })
  if (removal.removedRules > 0) console.log(`ocp-dev: removed Personal provider "${ZCODE_PROVIDER_ID}" from ${configPath}`)
  if (removal.clearedSelection) console.log("ocp-dev: the default model pointed at it; ZCode falls back to its own default")
  for (const path of [join(zcodeStateDir(), "bin"), join(zcodeStateDir(), "npm"), installRoot(), join(zcodeHome(), "config"), join(zcodeHome(), "cache")]) {
    if (existsSync(path)) removeManaged(path)
  }
  rmSync(manifestPath("zcode"), { force: true })
  console.log(`ocp-dev: zcode returned to factory state; upstream login and bridge credential kept in ${retainedStateDir()}`)
}
